// Generates the agent-facing files from the bundled module manifests (kiwifs
// `emit-fence-schemas` pattern), through Vite's SSR loader so aliases and JSON globs work:
//   ../../schemas/environment.v1.json  — environment JSON Schema with enums of real ids
//   ../../schemas/catalog.json         — every module and contribution (describeCatalog)
//   public/schema/environment.v1.json, public/catalog.json — the same two, for the dev server
//   public/catalog.md                  — the compact prompt (catalogPrompt)
//   ../../docs/modules-reference.md    — the same, for humans
//   ../../schemas/{plugin,ui-contributions,workspace}.v1.json, capabilities/*.json
//                                      — contract schemas (packages/plugin-contracts) for the kernel
//   ../../schemas/naming.json          — the naming config (packages/plugin-contracts/src/naming.ts)
//                                        for the Python kernel, worker, SDK, mcp.mjs and apps/agent
// Never hand-edit these. `--check` exits 1 if they're stale (CI drift check).
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { createServer } from "vite";

const root = new URL("..", import.meta.url).pathname;
const check = process.argv.includes("--check");


const server = await createServer({ root, configFile: join(root, "vite.config.ts"), server: { middlewareMode: true, hmr: false, watch: null }, appType: "custom", logLevel: "error" });
try {
  const m = await server.ssrLoadModule("/src/server-entry.ts");
  const schema = JSON.stringify(m.schema(), null, 2) + "\n";
  const catalog = JSON.stringify(m.catalog(), null, 2) + "\n";
  const files = {
    "../../schemas/environment.v1.json": schema,
    "../../schemas/catalog.json": catalog,
    "public/schema/environment.v1.json": schema,
    "public/catalog.json": catalog,
    "public/catalog.md": m.prompt(),
    "../../docs/modules-reference.md": `<!-- Generated by \`pnpm emit:schemas\` from the module manifests. Do not edit. -->\n\n${m.prompt()}`,
    "../../schemas/naming.json": JSON.stringify(m.NAMING, null, 2) + "\n",
    ...Object.fromEntries(Object.entries(m.contractSchemas()).map(([name, s]) => [`../../schemas/${name}`, JSON.stringify(s, null, 2) + "\n"])),
  };
  const stale = [];
  for (const [rel, text] of Object.entries(files)) {
    const path = join(root, rel);
    const before = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (before === text) continue;
    if (check) stale.push(rel);
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
      console.log(`wrote ${rel}`);
    }
  }
  if (stale.length) {
    console.error(`Generated files are stale; run \`pnpm emit:schemas\`:\n  ${stale.join("\n  ")}`);
    process.exitCode = 1;
  } else if (check) console.log("Generated schemas are up to date.");
} finally {
  await server.close();
}
