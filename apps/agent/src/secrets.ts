import { randomBytes } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export const SECRETS_DIR = resolve(import.meta.dirname, "../../../secrets");

/** Parse `KEY=VALUE` lines; `#` comments, blank lines, `export ` prefixes and surrounding quotes are allowed. */
export function parseEnvFile(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const m = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!m) continue;
    let value = m[2]!;
    const quoted = /^(['"])(.*)\1$/.exec(value);
    value = quoted ? quoted[2]! : value.replace(/\s+#.*$/, "");
    out[m[1]!] = value;
  }
  return out;
}

/**
 * Dev-only: merge `secrets/*.env` into `env` without overriding keys that are already set.
 * Returns the keys that were loaded (never values).
 */
export function loadDevSecrets(env: NodeJS.ProcessEnv = process.env, dir = SECRETS_DIR): string[] {
  if (env.APP_ENV === "production" || !existsSync(dir)) return [];
  const loaded: string[] = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".env")).sort()) {
    for (const [key, value] of Object.entries(parseEnvFile(readFileSync(join(dir, file), "utf8")))) {
      if (env[key] !== undefined && env[key] !== "") continue;
      if (value === "") continue;
      env[key] = value;
      loaded.push(key);
    }
  }
  return loaded;
}

/** Dev-only: create `secrets/agent.env` with a random service token if none is configured. */
export function ensureDevServiceToken(env: NodeJS.ProcessEnv = process.env, dir = SECRETS_DIR): void {
  if (env.APP_ENV === "production" || env.INTERNAL_AGENT_SERVICE_TOKEN) return;
  const token = randomBytes(32).toString("base64url");
  const file = join(dir, "agent.env");
  if (!existsSync(file)) {
    writeFileSync(file, `# Generated by apps/agent on first start. Bearer token for the Vite proxy.\nINTERNAL_AGENT_SERVICE_TOKEN=${token}\n`, { mode: 0o600 });
  }
  env.INTERNAL_AGENT_SERVICE_TOKEN = parseEnvFile(readFileSync(file, "utf8")).INTERNAL_AGENT_SERVICE_TOKEN ?? token;
}

/** `…5a3` for a set key, `missing` otherwise. Safe to log. */
export function maskSecret(value: string | undefined): string {
  if (!value) return "missing";
  return value.length <= 6 ? "set" : `set …${value.slice(-3)}`;
}
