#!/usr/bin/env node
// Builds registry/index.json, the curated plugin registry (docs/plugins.md §7.1), from
// plugins/*/plugin.yaml: one entry per plugin version with its artifact digest,
// capabilities, media types, runtime, permissions, licences (code, model and service terms
// kept apart), cost hints, compatibility and trust tier. Studio built-ins are listed as
// `builtin` so dependencies can name them. The digest algorithm matches
// apps/api/src/studio_api/plugins/digest.py.
//
//   node tools/build-registry.mjs           # write registry/index.json
//   node tools/build-registry.mjs --check   # exit 1 if it's stale
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const require = createRequire(join(root, "apps/web/package.json"));
const yaml = require("js-yaml");
const check = process.argv.includes("--check");
const naming = JSON.parse(readFileSync(join(root, "schemas/naming.json"), "utf8"));
const EXCLUDE = new Set(["node_modules", ".venv", "__pycache__", ".pytest_cache", ".ruff_cache", ".data"]);
const BUILTINS = ["core", "overlay2d", "cornerstone", "timeline", "presets"].map((n) => `${naming.namespace}.${n}`);

function files(dir, base = dir) {
  return readdirSync(dir)
    .flatMap((name) => {
      const p = join(dir, name);
      if (EXCLUDE.has(name)) return [];
      return statSync(p).isDirectory() ? files(p, base) : [relative(base, p).split("\\").join("/")];
    })
    .sort();
}

export function treeDigest(dir) {
  const h = createHash("sha256");
  for (const rel of files(dir)) h.update(`${rel}\0${createHash("sha256").update(readFileSync(join(dir, rel))).digest("hex")}\n`);
  return `sha256:${h.digest("hex")}`;
}

const entries = [];
for (const dir of readdirSync(join(root, "plugins")).sort()) {
  const file = join(root, "plugins", dir, "plugin.yaml");
  if (dir.startsWith("_") || !existsSync(file)) continue; // _template is the SDK template, not a plugin
  const manifest = yaml.load(readFileSync(file, "utf8"), { schema: yaml.JSON_SCHEMA });
  const providers = manifest.providers ?? [];
  entries.push({
    id: manifest.id,
    version: manifest.version,
    publisher: manifest.publisher,
    trustTier: manifest.publisher === "first-party" ? "first-party" : "vetted",
    artifactDigest: treeDigest(join(root, "plugins", dir)),
    path: `plugins/${dir}`,
    capabilities: (manifest.capabilities ?? []).map((c) => c.id),
    mediaTypes: [...new Set((manifest.capabilities ?? []).flatMap((c) => c.mediaTypes ?? []))].sort(),
    runtime: manifest.runtime?.kind,
    permissions: manifest.permissions,
    licenses: {
      code: manifest.license,
      models: Object.fromEntries(providers.filter((p) => p.modelLicense).map((p) => [p.id, p.modelLicense])),
      services: Object.fromEntries(providers.filter((p) => p.serviceTerms).map((p) => [p.id, p.serviceTerms])),
    },
    costHints: Object.fromEntries(providers.filter((p) => p.pricing).map((p) => [p.id, p.pricing])),
    compatibility: manifest.compatibility,
    manifest,
  });
}

const catalog = JSON.parse(readFileSync(join(root, "schemas/catalog.json"), "utf8"));
for (const m of catalog.modules.filter((m) => BUILTINS.includes(m.id))) {
  entries.push({
    id: m.id,
    version: m.version,
    publisher: "studio",
    trustTier: "builtin",
    artifactDigest: "builtin",
    path: null,
    capabilities: [],
    mediaTypes: [],
    runtime: "browser-bundled",
    permissions: { required: [], optional: [] },
    licenses: {},
    costHints: {},
    compatibility: { studio: "*", pluginApi: "^1" },
    manifest: { id: m.id, name: m.title, version: m.version, description: m.description, runtime: { kind: "browser-bundled" } },
  });
}

const out = JSON.stringify({ $comment: "Generated by tools/build-registry.mjs from plugins/*/plugin.yaml. Do not edit.", version: 1, plugins: entries }, null, 2) + "\n";
const target = join(root, "registry/index.json");
const before = existsSync(target) ? readFileSync(target, "utf8") : null;
if (check) {
  if (before !== out) {
    console.error("registry/index.json is stale; run node tools/build-registry.mjs");
    process.exit(1);
  }
  console.log("registry/index.json is up to date.");
} else if (before !== out) {
  writeFileSync(target, out);
  console.log(`wrote registry/index.json (${entries.length} entries)`);
} else console.log("registry/index.json unchanged.");
